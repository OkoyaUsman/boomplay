SONG_URL = "https://www.boomplay.com/songs/EQsDqYsdYKIHOAC2EfaGOCHr" # boomplay url to song page
SONG_ID = "275891736" # song id, this can be auto generated by the script, but boomplay guys are using cloudflare which sucks, although I can bypass it with a proxy, but it's not worth the effort, so we'll just use the hardcoded song id for now. Just look for data-cid in the song page html.

AES_KEY = b"boomplayVr3xopAM"
IV_KEY = b"boomplay8xIsKTn9"

def main():
    output_dir = Path("downloads")
    output_dir.mkdir(parents=True, exist_ok=True)
    session = curl_cffi.Session()

    try:
        song_url_id = extract_boomplay_url_id(SONG_URL)
        encrypted = encrypt(json.dumps({"itemID": song_url_id, "itemType": "MUSIC"}))
        music_response = session.post("https://android.boomplaymusic.com/BoomPlayer/content/resource/encrypt/getResourceAddrV2", data={"param": encrypted, "channel": "WEB"}).json()
        music_url = decrypt(music_response["source"])
        encrypted_key = encrypt(json.dumps({
            "channel": "WEB",
            "systemVersionCode": 0,
            "curClientVersionCode": 650,
            "imei": gen_imei(),
            "isH5": "T",
            "ua": UserAgent().chrome,
            "itemID": SONG_ID,
            "itemType": "MUSIC",
            "requestWay": "hlsAesKey"
        }))
        output_file = output_dir / f"{song_url_id}.mp3"
        with tempfile.TemporaryDirectory() as td:
            local = localize_playlist(music_url, f"https://android.boomplaymusic.com/BoomPlayer/resource/encrypt/getKey?param={urllib.parse.quote(encrypted_key)}&channel=WEB", Path(td), session)
            httpd = serve_dir(Path(td))
            try:
                cmd = [
                    "ffmpeg", "-y",
                    "-protocol_whitelist", "file,http,https,tcp,tls,crypto",
                    "-allowed_extensions", "ALL",
                    "-i", f"http://127.0.0.1:{httpd.server_address[1]}/{local.name}",
                    "-vn", "-c:a", "copy",
                    str(output_file),
                ]
                subprocess.run(cmd, check=True)
            finally:
                httpd.shutdown()
        print(f"Downloaded song to {output_file} successfully")
    except Exception as e:
        print(f"Error occured on line {e.__traceback__.tb_lineno}: {e}")

def extract_boomplay_url_id(url: str) -> str | None:
    path_parts = urllib.parse.urlparse(url).path.strip("/").split("/")
    if len(path_parts) >= 2 and path_parts[0] == "songs":
        return path_parts[1]
    return None

def encrypt(plaintext: str) -> str:
    plaintext_bytes = plaintext.encode('utf-8')
    padded = pad(plaintext_bytes, AES.block_size)
    cipher = AES.new(AES_KEY, AES.MODE_CBC, iv=IV_KEY)
    ciphertext = cipher.encrypt(padded)
    return base64.b64encode(ciphertext).decode('utf-8')

def decrypt(base64_ciphertext: str) -> str:
    ciphertext = base64.b64decode(base64_ciphertext)
    cipher = AES.new(AES_KEY, AES.MODE_CBC, iv=IV_KEY)
    padded_plaintext = cipher.decrypt(ciphertext)
    plaintext_bytes = unpad(padded_plaintext, AES.block_size)
    return plaintext_bytes.decode('utf-8')


def localize_playlist(playlist_url: str, key_url: str, tmp: Path, session: curl_cffi.Session) -> Path:
    playlist = session.get(playlist_url).text
    m = re.compile(r'#EXT-X-KEY:[^\n]*URI="([^"]+)"').search(playlist)
    if m:
        key = session.get(key_url).content
        print(key)
        if len(key) != 16:
            print(f"Warning: expected 16-byte AES key, got {len(key)} bytes")
        else:
            (tmp / "key.bin").write_bytes(key)
            playlist = playlist.replace(m.group(1), "key.bin")
            print(f"Key fetched and localized to {tmp / 'key.bin'}")

    lines = [
        urllib.parse.urljoin(playlist_url, line) if line and not line.startswith("#") else line
        for line in playlist.splitlines()
    ]
    out = tmp / "local.m3u8"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out

def serve_dir(directory: Path) -> ThreadingHTTPServer:
    handler = functools.partial(QuietHandler, directory=str(directory))
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd

def gen_imei() -> str:
    alphanumeric = "0123456789abcdefghijklmnopqrstuvwxyz"
    rand = "".join(random.choices(alphanumeric, k=13))
    out = []
    n = int(time.time() * 1000)
    while n:
        n, r = divmod(n, 36)
        out.append(alphanumeric[r])
    random_code = "".join(reversed(out))
    return f"{random.randint(0, 9)}_{random_code}_{rand}"[:16]


class QuietHandler(SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass


